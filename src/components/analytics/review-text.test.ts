/**
 * Plain-text review summary (Phase 6.4B): built from the SAME ReviewReport as the PDF, ES / EN,
 * no Markdown, no causes, no ratings, no opponent player names.
 */
import { describe, expect, it } from "vitest";
import { scenarioReport } from "@/server/analytics/report/report-fixtures";
import { analyticsTranslator } from "@/server/analytics/report/render-review-pdf";
import { REVIEW_QUESTION_KEYS, reviewQuestionKeys } from "./review-content";
import { describeReviewSignal, renderReviewPlainText } from "./review-text";

const es = analyticsTranslator("es");
const en = analyticsTranslator("en");
const three = scenarioReport("threeOfFive", { character: "aki" });
const all = scenarioReport("matchupExposure");
/** Intl separates "45,3 %" with a no-break space (kept in the output); compare with plain spaces. */
const nb = (text: string) => text.replace(/\u00a0/g, " ");
const plainEs = nb(renderReviewPlainText(three, es, "es"));
const plainEn = nb(renderReviewPlainText(all, en, "en"));

describe("renderReviewPlainText", () => {
  it("12/14. Spanish, selected character", () => {
    expect(plainEs.split("\n").slice(0, 4)).toEqual([
      "SST — REVISIÓN DE RENDIMIENTO",
      "",
      "A.K.I.",
      "Ranked · 90 días",
    ]);
    expect(plainEs).toContain("148 partidas registradas");
    expect(plainEs).toContain("67–81 · 45,3 % WR");
    expect(plainEs).toContain("PRIORIDADES PARA REVISAR");
    expect(plainEs).toContain("Generado por SST · Session Stats Tracker");
  });

  it("13/15. English, all characters (never posing as one character)", () => {
    expect(plainEn.split("\n").slice(0, 5)).toEqual([
      "SST — PERFORMANCE REVIEW",
      "",
      "Overview",
      "All my characters",
      "Ranked · 90 days",
    ]);
    expect(plainEn).toContain("120 recorded matches");
    expect(plainEn).toContain("Generated by SST · Session Stats Tracker");
  });

  it("16. priorities in the selected order, numbered", () => {
    const numbered = plainEs.split("\n").filter((l) => /^\d\. /.test(l));
    expect(numbered).toEqual([
      "1. DENTRO DE LA SESIÓN — Segunda mitad de sesión",
      "2. ENFRENTAMIENTO — A.K.I. vs JP",
      "3. PARTIDA SIGUIENTE — Resultados tras una derrota",
    ]);
    expect(three.priorities.map((p) => p.signal.id)).toEqual([
      "session-halves",
      "matchup:aki:jp",
      "post-loss",
    ]);
  });

  it("17/18. signed pp + arrow and sample sizes", () => {
    expect(plainEs).toContain("↓ -45,3 pp vs A.K.I. en general");
    expect(plainEs).toContain("41 decididas · A.K.I. en general: 45,3 % (148 decididas)");
    expect(plainEs).toContain("19 de 72 ganadas tras una derrota");
    expect(plainEn).toContain("↓ -13.9 pp vs A.K.I. overall");
    expect(plainEn).toContain("34 decided · A.K.I. overall: 49.2% (120 decided)");
    expect(plainEn).toContain("◆ Opponent with the most recorded matches");
  });

  it("19. every priority's predefined replay questions are included", () => {
    for (const p of three.priorities) {
      for (const key of reviewQuestionKeys(p.signal.type)) {
        expect(plainEs).toContain(`  • ${nb(es(`review.${key}`))}`);
      }
    }
    expect(plainEs).toContain(nb(es("review.disclaimer")));
  });

  it("omitted signals are mentioned, not listed", () => {
    expect(plainEs).toContain(
      "2 señales adicionales cumplieron los criterios de muestra y no se incluyen en este informe.",
    );
    expect(plainEn).not.toMatch(/additional signal/);
  });

  it("20. no causal / diagnostic / certainty wording", () => {
    const forbidden =
      /tilt|fatiga|fatigue|cansancio|coach|debilidad|weakness|counter|desventaja|disadvantage|significativ|significant|confianza|confidence|mejorando|improving|empeorando|getting worse|mental|resilien/i;
    for (const text of [plainEs, plainEn, renderReviewPlainText(three, en, "en")]) {
      expect(text).not.toMatch(forbidden);
    }
  });

  it("21. plain text: no Markdown syntax", () => {
    for (const text of [plainEs, plainEn]) {
      for (const line of text.split("\n")) {
        expect(line).not.toMatch(/^\s*(#|>|- |\* |```)/);
        expect(line).not.toMatch(/\*\*|__|`|\[[^\]]*\]\(/);
      }
    }
  });

  it("22/23. no rating and no opponent player name", () => {
    for (const text of [plainEs, plainEn]) {
      expect(text).not.toMatch(/\bLP\b|\bMR\b|rating|Master Rate|League Points/);
      expect(text).not.toMatch(/OPPONENT_SECRET|opponent_name/);
    }
  });

  it("is deterministic", () => {
    expect(nb(renderReviewPlainText(three, es, "es"))).toBe(plainEs);
  });
});

describe("shared review wording", () => {
  it("one question-key source for every surface", () => {
    expect(reviewQuestionKeys("post-loss-transition")).toEqual(
      REVIEW_QUESTION_KEYS["post-loss-transition"].map((q) => `questions.postLoss.${q}`),
    );
  });

  it("describeReviewSignal reads the signal's own evidence", () => {
    const p = all.priorities[0]!.signal;
    const text = describeReviewSignal(p, (k, v) => es(`review.${k}`, v), "es");
    expect(text.title).toBe("A.K.I. vs JP");
    expect(nb(text.value)).toBe("35,3 %");
    expect(text.arrow).toBe("↓");
  });
});
